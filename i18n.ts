export const dict = { de, en };
export type Dict = typeof de;
type StringKey = { [K in keyof Dict]: Dict[K] extends string ? K : never }[keyof Dict];

export function makeT(lang: Lang) {
  const d = dict[lang];
  return (key: StringKey, vars?: Record<string, string | number>) => {
    let s = d[key] as string;
    if (vars) for (const k in vars) s = s.replace('{' + k + '}', String(vars[k]));
    return s;
  };
}

export type T = ReturnType<typeof makeT>;

export const I18n = createContext<{ lang: Lang; t: T; setLang: (l: Lang) => void }>({
  lang: 'de',
  t: makeT('de'),
  setLang: () => {},
});

export const useI18n = () => useContext(I18n);

export function initialLang(): Lang {
  try {
    const saved = localStorage.getItem('kolumna:lang');
    if (saved === 'de' || saved === 'en') return saved;
  } catch { /* ignore */ }
  return typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('de') ? 'de' : 'en';
}
